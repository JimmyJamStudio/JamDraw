// Things done to the selection: duplicate, copy / cut / paste, group, arrange, flip, align, combine, outline stroke,
// sticker outline, colors and opacity, and what happens when they can't work.
module.exports = (test) => {
  test('actions: copy, paste, duplicate, group', async (t) => {
    const { check, app, key, combo, add, count, button, toastText } = t;
    await key('v');
    await combo('Control', 'v');
    check(await count() === 0, 'paste with nothing copied does nothing');
    await combo('Control', 'c');
    check(await toastText() === 'Select something first', 'copy with nothing selected says so');
    await combo('Control', 'd');
    check(await toastText() === 'Select something first', 'duplicate with nothing selected says so');
    await add({ x: 100, y: 100, w: 100, h: 100 }, { x: 300, y: 100, w: 100, h: 100 });
    await t.sel(0);
    await combo('Control', 'd');
    check(await count() === 3, 'Ctrl+D duplicates');
    await button('#options', 'Duplicate');
    check(await count() === 4, 'the Duplicate button too');
    await combo('Control', 'c');
    check(await toastText() === 'Copied 1', 'Ctrl+C copies');
    await combo('Control', 'v');
    check(await count() === 5, 'Ctrl+V pastes');
    await combo('Control', 'x');
    check(await count() === 4, 'Ctrl+X cuts');
    await combo('Control', 'v');
    check(await count() === 5, 'and it pastes back');
    await button('#options', 'Delete');
    check(await count() === 4, 'the Delete button deletes');
    await t.sel(0);
    await button('#options', 'Group');
    check(await toastText() === 'Select 2 or more shapes', 'grouping needs two things');
    await t.sel(0, 1);
    await button('#arrange', 'Group');
    check(await app(() => __jamdraw.paper.project.activeLayer.children.some((c) => c.className === 'Group')), 'the Group button groups');
    await app(() => { const l = __jamdraw.paper.project.activeLayer; __jamdraw.setSel(l.children.slice()); });
    await button('#arrange', 'Ungroup');
    check(await app(() => !__jamdraw.paper.project.activeLayer.children.some((c) => c.className === 'Group') && __jamdraw.S.sel.length === 4), 'ungroup takes groups apart and keeps the rest selected');
    await button('#options', 'Ungroup');
    check(await app(() => __jamdraw.S.sel.length) === 4, 'ungrouping plain shapes leaves them alone');
  });

  test('actions: arrange, flip, align', async (t) => {
    const { check, app, add, button, combo, key, toastText } = t;
    const order = () => app(() => __jamdraw.paper.project.activeLayer.children.map((c) => Math.round(c.bounds.x)).join(','));
    await add({ x: 0, y: 0, w: 50, h: 50 }, { x: 100, y: 0, w: 50, h: 50 }, { x: 200, y: 0, w: 50, h: 50 });
    await key('v');
    await button('#arrange', 'To front');
    check(await toastText() === 'Select something first', 'arranging needs a selection');
    await t.sel(0);
    await button('#arrange', 'To front');
    check(await order() === '100,200,0', 'To front');
    await button('#arrange', 'To back');
    check(await order() === '0,100,200', 'To back');
    await button('#arrange', 'Forward');
    check(await order() === '100,0,200', 'Forward');
    await button('#arrange', 'Backward');
    check(await order() === '0,100,200', 'Backward');
    await key(']');
    check(await order() === '100,0,200', '] moves forward');
    await key('[');
    check(await order() === '0,100,200', '[ moves backward');
    await combo('Control', ']');
    check(await order() === '100,200,0', 'Ctrl+] to front');
    await combo('Control', '[');
    check(await order() === '0,100,200', 'Ctrl+[ to back');
    await t.sel(0, 1);
    await button('#arrange', 'Forward');
    check(await order() === '200,0,100', 'two together move forward past the next one');
    await button('#arrange', 'Backward');
    check(await order() === '0,100,200', 'and back');
    await t.sel(1, 2);
    await button('#arrange', 'Forward');
    check(await order() === '0,100,200', 'the top ones can not go further forward');
    await t.sel(0, 1);
    await button('#arrange', 'Backward');
    check(await order() === '0,100,200', 'the bottom ones can not go further back');

    await app(() => { const l = __jamdraw.paper.project.activeLayer; l.removeChildren(); });
    await t.add({ kind: 'line', pts: [[100, 100], [300, 200]], stroke: '#000', width: 4 });
    await t.sel(0);
    await button('#options', 'Flip ↔');
    check(await app(() => { const s = __jamdraw.paper.project.activeLayer.firstChild.segments; return Math.round(s[0].point.x) === 300 && Math.round(s[0].point.y) === 100; }), 'Flip ↔ mirrors left to right');
    await button('#options', 'Flip ↕');
    check(await app(() => { const s = __jamdraw.paper.project.activeLayer.firstChild.segments; return Math.round(s[0].point.y) === 200; }), 'Flip ↕ mirrors top to bottom');
    await t.sel();
    await button('#options', 'Flip ↔');
    check(await toastText() === 'Select something first', 'flipping needs a selection');

    await app(() => __jamdraw.paper.project.activeLayer.removeChildren());
    await t.add({ x: 100, y: 100, w: 100, h: 100 }, { x: 300, y: 250, w: 50, h: 200 });
    await t.sel(0, 1);
    const boxes = () => app(() => __jamdraw.paper.project.activeLayer.children.map((c) => [Math.round(c.bounds.left), Math.round(c.bounds.top), Math.round(c.bounds.right), Math.round(c.bounds.bottom)]));
    await button('#align', 'Left');
    let b = await boxes();
    check(b[0][0] === 100 && b[1][0] === 100, 'align left');
    await button('#align', 'Right');
    b = await boxes();
    check(b[0][2] === b[1][2], 'align right');
    await button('#align', 'Center');
    b = await boxes();
    check(b[0][0] + b[0][2] === b[1][0] + b[1][2], 'align center');
    await button('#align', 'Top');
    b = await boxes();
    check(b[0][1] === b[1][1], 'align top');
    await button('#align', 'Bottom');
    b = await boxes();
    check(b[0][3] === b[1][3], 'align bottom');
    await button('#align', 'Middle');
    b = await boxes();
    check(b[0][1] + b[0][3] === b[1][1] + b[1][3], 'align middle');
    await button('#align', 'Center on page');
    const u = await app(() => { const l = __jamdraw.paper.project.activeLayer; const r = l.children[0].bounds.unite(l.children[1].bounds); return [Math.round(r.center.x), Math.round(r.center.y)]; });
    check(u[0] === 512 && u[1] === 512, 'Center on page centers the two as one block');
    await t.sel(0);
    await button('#align', 'Left');
    check(await app(() => Math.round(__jamdraw.paper.project.activeLayer.firstChild.bounds.left)) === 0, 'one thing aligns to the page');
    await button('#align', 'Center on page');
    check(await app(() => Math.round(__jamdraw.paper.project.activeLayer.firstChild.bounds.center.x)) === 512, 'and centers on it');
    await t.sel();
    await button('#align', 'Left');
    check(await toastText() === 'Select something first', 'aligning needs a selection');
  });

  test('actions: combine shapes', async (t) => {
    const { check, app, add, button, toastText } = t;
    const area = () => app(() => Math.round(Math.abs(__jamdraw.S.sel[0].area)));
    const setup = async () => {
      await app(() => __jamdraw.paper.project.activeLayer.removeChildren());
      await add({ x: 100, y: 100, w: 200, h: 200 }, { x: 200, y: 100, w: 200, h: 200 });
      await t.sel(0, 1);
    };
    await t.key('v');
    await setup(); await button('#combine', 'Unite');
    check(await area() === 60000, 'Unite');
    await setup(); await button('#combine', 'Subtract');
    check(await area() === 20000, 'Subtract cuts the top shape out of the bottom one');
    await setup(); await button('#combine', 'Intersect');
    check(await area() === 20000, 'Intersect keeps the overlap');
    await setup(); await button('#combine', 'Exclude');
    const ex = await app(() => { const s = __jamdraw.S.sel[0]; return { area: Math.round(Math.abs(s.area)), kids: s.children ? s.children.map((c) => Math.round(c.area)) : null }; });
    check(ex.kids && ex.kids.reduce((a, b) => a + Math.abs(b), 0) === 40000, 'Exclude keeps what does not overlap ' + JSON.stringify(ex));
    await t.sel(0);
    await button('#combine', 'Unite');
    check(await toastText() === 'Select 2 or more shapes (ungroup groups first)', 'combining needs two shapes');
    await setup();
    await app(() => { window.__realUnite = paper.PathItem.prototype.unite; paper.PathItem.prototype.unite = () => { throw new Error('nope'); }; });
    await button('#combine', 'Unite');
    await app(() => { paper.PathItem.prototype.unite = window.__realUnite; });
    check(await toastText() === 'Those shapes could not be combined', 'a failed combine says so and changes nothing');
    check(await t.count() === 2, '(both shapes still there)');
  });

  test('actions: outline stroke and sticker outline', async (t) => {
    const { check, app, add, button, toastText, count } = t;
    await t.key('v');
    await button('#combine', 'Outline stroke');
    check(await toastText() === 'Select something first', 'outline stroke needs a selection');
    await add({ x: 100, y: 100, w: 100, h: 100 });
    await t.sel(0);
    await button('#combine', 'Outline stroke');
    check(await toastText() === 'Nothing selected has a stroke', 'shapes without a stroke are left alone');
    await add({ x: 300, y: 100, w: 100, h: 100, fill: '#f2c14e', stroke: '#1d1418', width: 10 });
    await app(() => { const it = __jamdraw.paper.project.activeLayer.lastChild; it.strokeJoin = 'miter'; it.strokeCap = 'butt'; });
    await t.sel(1);
    await button('#combine', 'Outline stroke');
    const res = await app(() => __jamdraw.S.sel.map((s) => ({ fill: s.fillColor && s.fillColor.toCSS(true), stroke: !!s.strokeColor })));
    check(res.length === 2 && res.some((r) => r.fill === '#1d1418') && res.some((r) => r.fill === '#f2c14e' && !r.stroke), 'a filled shape keeps its fill and gets its stroke as a separate shape (miter join)');
    await add({ kind: 'line', pts: [[100, 400], [400, 450]], stroke: '#1d1418', width: 8 });
    await t.sel(-1);
    await app(() => { window.__realOS = paperjsOffset.offsetStroke; paperjsOffset.offsetStroke = () => { throw new Error('nope'); }; });
    await button('#combine', 'Outline stroke');
    await app(() => { paperjsOffset.offsetStroke = window.__realOS; });
    check(await toastText() === 'Nothing selected has a stroke', 'if outlining fails the line is kept as it is');

    await app(() => __jamdraw.paper.project.activeLayer.removeChildren());
    await t.sel();
    await button('#combine', 'Sticker outline');
    check(await toastText() === 'Select something first', 'sticker outline needs a selection');
    await app(() => { const g = new paper.Group(); __jamdraw.paper.project.activeLayer.addChild(g); __jamdraw.setSel([g]); });
    await button('#combine', 'Sticker outline');
    check(await toastText() === 'Nothing to outline', 'an empty group has nothing to outline');
    await app(() => __jamdraw.paper.project.activeLayer.removeChildren());
    await add({ x: 100, y: 100, w: 100, h: 100 }, { x: 150, y: 150, w: 100, h: 100 }, { kind: 'line', pts: [[300, 300], [450, 320]], stroke: '#000', width: 12 });
    await app(() => { const l = __jamdraw.paper.project.activeLayer; const g = new paper.Group([l.children[0], l.children[1]]); l.insertChild(0, g); __jamdraw.setSel(l.children.slice()); });
    const n = await count();
    await button('#combine', 'Sticker outline');
    check(await count() === n + 1 && await app(() => __jamdraw.paper.project.activeLayer.firstChild.fillColor.toCSS(true)) === '#1d1418', 'sticker outline goes around groups and lines, underneath, in the stroke color');
    await app(() => { window.__realOS = paperjsOffset.offsetStroke; paperjsOffset.offsetStroke = () => { throw new Error('nope'); }; });
    await t.sel(-1);
    await button('#combine', 'Sticker outline');
    await app(() => { paperjsOffset.offsetStroke = window.__realOS; });
    check(await count() === n + 2, 'if a line can not be thickened it is outlined as it is');
    await app(() => { window.__realOff = paperjsOffset.offset; paperjsOffset.offset = () => { throw new Error('nope'); }; });
    t.expectConsoleErrors(1);
    await t.sel(-1);
    await button('#combine', 'Sticker outline');
    await app(() => { paperjsOffset.offset = window.__realOff; });
    check(await toastText() === 'Could not build the outline for that selection', 'a failed sticker outline says so');
  });

  test('actions: colors, width, opacity on the selection', async (t) => {
    const { check, app, add, page, toastText } = t;
    await t.key('v');
    await add({ x: 100, y: 100, w: 100, h: 100 }, { x: 300, y: 100, w: 100, h: 100 });
    await app(() => { const l = __jamdraw.paper.project.activeLayer; const g = new paper.Group([l.children[0], l.children[1]]); l.addChild(g); });
    await t.sel(0);
    // Colour applies through groups.
    await page.click('[data-chip="fill"]');
    await page.$eval('#hex', (el) => { el.value = '#123456'; el.dispatchEvent(new Event('change')); });
    check(await app(() => __jamdraw.paper.project.activeLayer.firstChild.children.every((c) => c.fillColor.toCSS(true) === '#123456')), 'a hex color fills everything in a group');
    await page.$eval('#hex', (el) => { el.value = 'abc'; el.dispatchEvent(new Event('change')); });
    check(await app(() => __jamdraw.S.fill) === '#abc', 'hex without # works');
    await page.$eval('#hex', (el) => { el.value = 'banana'; el.dispatchEvent(new Event('change')); });
    check(await toastText() === 'Use a hex color like #d22a5a', 'a bad hex color says so');
    await page.$eval('#hex', (el) => { el.value = 'none'; el.dispatchEvent(new Event('change')); });
    check(await app(() => __jamdraw.paper.project.activeLayer.firstChild.firstChild.fillColor === null), 'none removes the fill');
    await page.$eval('#hex', (el) => { el.value = '#ff000080'; el.dispatchEvent(new Event('change')); });
    await t.sel(0);
    check(await app(() => __jamdraw.S.fill) === '#ff000080', 'a see-through color reads back with its alpha');
    await page.click('[data-chip="stroke"]');
    await page.$eval('#colorpick', (el) => { el.value = '#00ff00'; el.dispatchEvent(new Event('input')); });
    check(await app(() => __jamdraw.paper.project.activeLayer.firstChild.firstChild.strokeColor === null), 'a live stroke color skips shapes with no stroke width');
    await page.$eval('#sw-range', (el) => { el.value = '6'; el.dispatchEvent(new Event('input')); });
    check(await app(() => __jamdraw.paper.project.activeLayer.firstChild.firstChild.strokeWidth) === 6, 'dragging the width slider shows it live, adding the stroke');
    await page.$eval('#sw-range', (el) => { el.value = '9'; el.dispatchEvent(new Event('change')); });
    await page.$eval('#sw-num', (el) => { el.value = '12'; el.dispatchEvent(new Event('change')); });
    check(await app(() => __jamdraw.paper.project.activeLayer.firstChild.firstChild.strokeWidth) === 12, 'the width box sets it');
    await page.$eval('#colorpick', (el) => { el.value = '#0000ff'; el.dispatchEvent(new Event('input')); el.dispatchEvent(new Event('change')); });
    check(await app(() => __jamdraw.paper.project.activeLayer.firstChild.firstChild.strokeColor.toCSS(true)) === '#0000ff', 'the color picker sets the stroke');
    await t.act('color-none');
    check(await app(() => __jamdraw.paper.project.activeLayer.firstChild.firstChild.strokeColor === null), 'None removes the stroke');
    await page.$eval('#sw-num', (el) => { el.value = 'x'; el.dispatchEvent(new Event('change')); });
    check(await app(() => __jamdraw.S.strokeWidth) === 0, 'a width that is not a number counts as 0');
    await t.add({ x: 600, y: 600, w: 50, h: 50 });
    await t.sel(-1);
    await app(() => { __jamdraw.S.stroke = '#334455'; });
    await page.$eval('#sw-num', (el) => { el.value = '3'; el.dispatchEvent(new Event('change')); });
    check(await app(() => { const it = __jamdraw.paper.project.activeLayer.lastChild; return it.strokeWidth === 3 && it.strokeColor.toCSS(true) === '#334455'; }), 'setting a width on a shape with no stroke gives it the stroke color');
    await page.click('[data-chip="fill"]');
    await page.$eval('#colorpick', (el) => { el.value = '#ffaa00'; el.dispatchEvent(new Event('input')); });
    check(await app(() => __jamdraw.paper.project.activeLayer.lastChild.fillColor.toCSS(true)) === '#ffaa00', 'dragging the color picker recolors the fill live');
    await t.sel(0);
    await page.$eval('#op-range', (el) => { el.value = '40'; el.dispatchEvent(new Event('input')); el.dispatchEvent(new Event('change')); });
    check(await app(() => __jamdraw.paper.project.activeLayer.firstChild.opacity) === 0.4, 'opacity');
    await app(() => { __jamdraw.S.fill = '#111111'; __jamdraw.S.stroke = '#222222'; });
    await t.key('x');
    check(await app(() => __jamdraw.S.fill === '#222222' && __jamdraw.S.stroke === '#111111'), 'X swaps fill and stroke');
    await t.act('swap-colors');
    await t.sel();
    await t.act('color-none');
    check(await app(() => __jamdraw.S.fill) === null, 'None with nothing selected just changes the current color');
    await app(() => { const g = new paper.Group(); __jamdraw.paper.project.activeLayer.addChild(g); __jamdraw.setSel([g]); });
    check(await app(() => __jamdraw.S.sel.length) === 1, 'selecting an empty group does not break the color panel');
  });
};
